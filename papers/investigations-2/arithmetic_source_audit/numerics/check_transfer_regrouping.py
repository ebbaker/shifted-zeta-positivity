def require(condition, message):
    if not condition:
        raise AssertionError(message)


def divisors(n):
    factors = [p for p in NORMS if n % p == 0]
    return sorted(prod(p for p, use in zip(factors, bits) if use)
                  for bits in product((0, 1), repeat=len(factors)))


def mu(n):
    return (-1) ** sum(n % p == 0 for p in NORMS)


def dyadic(n):
    return 1 << (n.bit_length() - 1)


def preimages(r, f, k):
    """Source lines 2550--2568: retain every sign before summing."""
    f_primes = [p for p in NORMS if f % p == 0]
    for t in divisors(r):
        for locations in product(range(3), repeat=len(f_primes)):
            C, e, w = (prod(p for p, place in zip(f_primes, locations)
                            if place == target) for target in range(3))
            if k % e or gcd(w, k) != 1:
                continue
            for d in divisors(gcd(C, k)):
                g, h = e * (r // t), k // (d * e)
                yield dict(C=C, d=d, t=t, g=g, e=e, w=w, h=h,
                           sign=mu(e) * mu(w))


def check_normalizations(entry, r, f, k, H, L, F, Sigma, c):
    C, d, t, g, e, w, h = (entry[name] for name in
                            ("C", "d", "t", "g", "e", "w", "h"))
    require(gcd(g, C * t) == gcd(w, g * C * t * h) == 1,
            "source coprimality masks")
    require(g % e == C % d == 0, "source divisors")
    require(t * g // e == r and C * e * w == f and d * e * h == k,
            "return map")
    ell = L / (C * t)
    outer_weight = H * C / (d * L**2 * F)
    Y = c * Sigma * L * F * d / (H * C**2)
    require(ell / (g * w) == L / (r * f), "individual column scale")
    require(outer_weight * Y * g / (e * ell) == c * Sigma * r / L**2,
            "combined normalization")
    require(Y * h * g**2 / (e * ell**2)
            == c * Sigma * F * k * r**2 / (H * L), "Fourier parameter")


