"""Independent exact verification for k=2,3 and ARBITRARY monic real p:
   let D = det M(x) - P_p(x) as a polynomial in x_0..x_3.
   Claim: S := 2*sum_{a>=1} tr(T_a^2) + 3*||lam||^2   lies in the ideal generated by
   the coefficients of D.  If so, D==0 forces S=0, hence T_1=T_2=T_3=0, lam=0 over R.
   We prove membership constructively: S = (Q-linear combo of coeffs of D) + (poly multiples
   of the AFFINE-LINEAR coeffs of D)."""
import sympy as sp, itertools, sys

def run(k):
    x=sp.symbols('x0 x1 x2 x3', real=True)
    T=[sp.Matrix(k,k,lambda i,j: sp.Symbol('T%d_%d%d'%(a,min(i,j),max(i,j)),real=True)) for a in range(4)]
    L=sp.Matrix(4,k,lambda a,j: sp.Symbol('l%d_%d'%(a,j),real=True))   # lam_j = sum_a l_a_j e_a
    C=sum((Ta*Ta for Ta in T), sp.zeros(k,k)) + L.T*L
    M=C + sum(xx**2 for xx in x)*sp.eye(k) - 2*sum((x[a]*T[a] for a in range(4)), sp.zeros(k,k))
    # P_p with symbolic monic p:  p(z)=z^k + c_{k-1} z^{k-1} + ... + c_0
    c=[sp.Symbol('c%d'%m) for m in range(k)]
    z=sp.Symbol('z'); pz=z**k+sum(c[m]*z**m for m in range(k))
    r2=x[1]**2+x[2]**2+x[3]**2
    w=sp.Symbol('w')
    # P_p = p(x0+i r) p(x0-i r): compute as resultant-free product using i*r symbolic
    ii=sp.I; rr=sp.Symbol('rr')  # rr stands for r, then substitute rr^2 -> r2
    prod=sp.expand(pz.subs(z,x[0]+ii*rr)*pz.subs(z,x[0]-ii*rr))
    prod=sp.expand(sp.re(sp.expand(prod)) if False else prod)
    prod=sp.expand(prod)
    # prod is a polynomial in rr with only even powers; substitute rr^2 = r2
    P=sp.Poly(prod,rr); Pp=0
    for (e,),co in P.terms():
        assert e%2==0, e
        Pp+= sp.expand(co)*r2**(e//2)
    Pp=sp.expand(Pp)
    D=sp.expand(sp.det(M)-Pp)
    Dp=sp.Poly(D,*x)
    coeffs=[sp.expand(v) for v in Dp.coeffs()]
    unk=sorted(set().union(*[cc.free_symbols for cc in coeffs])-set(c), key=str)
    # split into affine-linear ones (deg<=1 in unknowns) and the rest
    lin=[cc for cc in coeffs if sp.Poly(cc,*unk).total_degree()<=1]
    S=sp.expand(2*sum(sp.trace(T[a]*T[a]) for a in (1,2,3)) + 3*sum(L[a,j]**2 for a in range(4) for j in range(k)))
    # reduce S and all coeffs modulo the linear equations by solving them
    sol=sp.solve(lin, unk, dict=True)
    print(' k=%d : #coeff eqs=%d, #affine-linear eqs=%d, #linear-solution branches=%d'%(k,len(coeffs),len(lin),len(sol)))
    assert len(sol)==1
    sub=sol[0]
    Sr=sp.expand(S.subs(sub))
    Cr=[sp.expand(cc.subs(sub)) for cc in coeffs]
    Cr=[cc for cc in Cr if cc!=0]
    # is Sr a Q(c)-linear combination of Cr?  solve linear system over the monomial basis
    mons=set()
    allp=[sp.Poly(t, *[u for u in unk if u not in sub]) for t in Cr+[Sr]]
    vars2=[u for u in unk if u not in sub]
    for pp in allp: mons|=set(pp.monoms())
    mons=sorted(mons)
    import sympy.matrices as smx
    A=sp.Matrix([[sp.Poly(cc,*vars2).coeff_monomial(m) for cc in Cr] for m in mons])
    b=sp.Matrix([[sp.Poly(Sr,*vars2).coeff_monomial(m)] for m in mons])
    ys=sp.symbols('y0:%d'%len(Cr))
    solL=sp.solve(list(A*sp.Matrix(ys)-b), ys, dict=True)
    ok = len(solL)>0
    print('   S in span of coeffs (after using the linear eqs): %s'%ok)
    if ok:
        yv=solL[0]
        used={str(ys[i]):sp.simplify(yv.get(ys[i],ys[i])) for i in range(len(Cr))}
        nz={kk:vv for kk,vv in used.items() if vv!=0 and not vv.free_symbols & set(ys)}
        print('   nonzero multipliers used: %d'%len(nz))
        # verify residual exactly
        chk=sp.expand(Sr - sum(sp.simplify(yv.get(ys[i],0))*Cr[i] for i in range(len(Cr))))
        print('   exact verification of the identity: %s'%(sp.simplify(chk)==0))
    return ok

for k in [2,3]:
    run(k)
